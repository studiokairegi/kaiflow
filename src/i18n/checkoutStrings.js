export const checkoutT = (lang) => makeTranslator(CHECKOUT_STRINGS, lang);

// Server errors that carry a code are shown in the page language; anything else uses the page's own fallback text.
// (The English Edge Function messages are only ever shown on English pages.)
export function localizeError(err, t, fallbackKey) {
  if (t.lang === "en") return err?.message || t(fallbackKey);
  const byCode = err?.code && CHECKOUT_STRINGS.ja[`error.${err.code}`];
  return byCode || t(fallbackKey);
}
