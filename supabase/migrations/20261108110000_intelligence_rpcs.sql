     set state = case when attempts >= max_attempts then 'dead' else 'queued' end,
         locked_by = null, lease_until = null, updated_at = now(),
         last_error = left(coalesce(last_error, '') || ' [lease expired]', 1000)
   where organization_id = v_org and state = 'running' and lease_until < now();
