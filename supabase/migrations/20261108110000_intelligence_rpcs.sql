create or replace function public.intel_agent_resolve_lead(p_prospect_id uuid) returns jsonb
language plpgsql security definer set search_path = pg_catalog, public as $$
declare v_org uuid := public.intel_agent_org(); s public.intel_settings; p public.intel_prospects; l public.leads;
        v_matches jsonb; v_top record; v_lead uuid; v_contacted boolean;
begin
  select * into s from public.intel_settings where organization_id = v_org;
  perform pg_advisory_xact_lock(hashtext(v_org::text || ':lead'));      -- serialises lead creation: no duplicate races
  select * into p from public.intel_prospects where id = p_prospect_id and organization_id = v_org for update;
  if not found then raise exception 'prospect not found'; end if;
  if p.lead_id is not null then return jsonb_build_object('action', 'already_linked', 'lead_id', p.lead_id); end if;
  if p.status <> 'qualified' then return jsonb_build_object('action', 'not_qualified', 'status', p.status); end if;

  select coalesce(jsonb_agg(jsonb_build_object('lead_id', d.lead_id, 'confidence', d.confidence, 'reason', d.reason)), '[]'::jsonb)
    into v_matches from public.crm_find_lead_duplicates(s.owner_user_id, p.name, p.website, p.contact_email, p.contact_name, null) d;
  select * into v_top from public.crm_find_lead_duplicates(s.owner_user_id, p.name, p.website, p.contact_email, p.contact_name, null) limit 1;

  if v_top.lead_id is not null and v_top.confidence = 'very_high' then
    select * into l from public.leads where id = v_top.lead_id;
    v_contacted := l.last_contacted_at is not null or l.stage <> 'pool' or coalesce((l.emails -> 0 ->> 'sent')::boolean, false);
    update public.intel_prospects
       set lead_id = l.id, status = 'lead_linked', updated_at = now(),
           facts = jsonb_set(facts, '{estimates}', coalesce(facts -> 'estimates', '{}'::jsonb) || jsonb_build_object('already_contacted', v_contacted))
     where id = p.id;
    perform public._intel_log(v_org, 'agent', 'link_existing_lead', 'prospect', p.id::text, jsonb_build_object('lead_id', l.id, 'source_kind', l.source_kind, 'already_contacted', v_contacted));
    return jsonb_build_object('action', case when l.source_kind = 'ai_intelligence' then 'linked_ai' else 'linked_manual' end,
                              'lead_id', l.id, 'already_contacted', v_contacted);
  elsif v_top.lead_id is not null then
    update public.intel_prospects set status = 'needs_review', review_reason = 'possible duplicate of an existing lead (' || v_top.confidence || ')',
           facts = jsonb_set(facts, '{estimates}', coalesce(facts -> 'estimates', '{}'::jsonb) || jsonb_build_object('duplicate_candidates', v_matches)), updated_at = now()
     where id = p.id;
    perform public._intel_log(v_org, 'agent', 'duplicate_review', 'prospect', p.id::text, jsonb_build_object('matches', v_matches));
    perform public._intel_notify(v_org, 'intel_needs_review', 'Possible duplicate needs review: ' || p.name,
                                 'KairFlow Intelligence found a prospect that may already be a lead. Review before any outreach.',
                                 null, p.id, null, 'dup:' || p.id::text);
    return jsonb_build_object('action', 'review', 'matches', v_matches);
  end if;

  v_lead := public._intel_create_ai_lead(v_org, p.id, auth.uid());
  perform public._intel_log(v_org, 'agent', 'create_ai_lead', 'lead', v_lead::text, jsonb_build_object('prospect_id', p.id));
  return jsonb_build_object('action', 'created', 'lead_id', v_lead);
end $$;

