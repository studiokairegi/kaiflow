create or replace function public.intel_admin_update_settings(p_patch jsonb) returns jsonb
language plpgsql security definer set search_path = pg_catalog, public as $$
declare v_org uuid := public.intel_admin_org(); s public.intel_settings;
begin
  select * into s from public.intel_settings where organization_id = v_org for update;
  if not found then raise exception 'Run setup first (intel_admin_bootstrap)'; end if;
  if p_patch ? 'timezone' then perform now() at time zone (p_patch ->> 'timezone'); end if;
  if (p_patch ->> 'autonomy') = 'autonomous' and (s.sender_email = '' or s.physical_address = '') then
    raise exception 'Set the sender email and physical address before enabling autonomous mode';
  end if;
  update public.intel_settings set
    autonomy = coalesce(p_patch ->> 'autonomy', autonomy),
    daily_initial_cap = coalesce((p_patch ->> 'daily_initial_cap')::int, daily_initial_cap),
    daily_followup_cap = coalesce((p_patch ->> 'daily_followup_cap')::int, daily_followup_cap),
    allow_cap_shift = coalesce((p_patch ->> 'allow_cap_shift')::boolean, allow_cap_shift),
    followup_business_days = coalesce((p_patch ->> 'followup_business_days')::int, followup_business_days),
    max_followups = coalesce((p_patch ->> 'max_followups')::int, max_followups),
    warmup_enabled = coalesce((p_patch ->> 'warmup_enabled')::boolean, warmup_enabled),
    timezone = coalesce(p_patch ->> 'timezone', timezone),
    sender_name = coalesce(p_patch ->> 'sender_name', sender_name),
    sender_email = coalesce(p_patch ->> 'sender_email', sender_email),
    physical_address = coalesce(p_patch ->> 'physical_address', physical_address),
    opt_out_text = coalesce(nullif(btrim(p_patch ->> 'opt_out_text'), ''), opt_out_text),
    max_auto_replies_per_thread = coalesce((p_patch ->> 'max_auto_replies_per_thread')::int, max_auto_replies_per_thread),
    updated_at = now(), updated_by = auth.uid()
   where organization_id = v_org;
  perform public._intel_log(v_org, 'admin', 'update_settings', 'settings', v_org::text, p_patch);
  return to_jsonb((select x from public.intel_settings x where x.organization_id = v_org));
end $$;

create or replace function public.intel_admin_set_kill_switch(p_on boolean) returns jsonb
language plpgsql security definer set search_path = pg_catalog, public as $$
declare v_org uuid := public.intel_admin_org(); s public.intel_settings;
begin
  select * into s from public.intel_settings where organization_id = v_org for update;
  if not found then raise exception 'Run setup first (intel_admin_bootstrap)'; end if;
  if p_on is false then
    if s.sender_email = '' or s.physical_address = '' or btrim(s.opt_out_text) = '' then
      raise exception 'Set sender email, physical address and opt-out text before enabling sending';
    end if;
    if not exists (select 1 from public.intel_mail_account a where a.organization_id = v_org and a.status = 'connected') then
      raise exception 'Connect Zoho Mail before enabling sending';
    end if;
    if s.agent_user_id is null then raise exception 'Register the agent identity before enabling sending'; end if;
  end if;
  update public.intel_settings
     set kill_switch = p_on,
         warmup_started_on = case when p_on is false and warmup_started_on is null then public._intel_today(v_org) else warmup_started_on end,
         updated_at = now(), updated_by = auth.uid()
   where organization_id = v_org;
  perform public._intel_log(v_org, 'admin', case when p_on then 'kill_switch_on' else 'kill_switch_off' end, 'settings', v_org::text, '{}'::jsonb);
  return jsonb_build_object('kill_switch', p_on);
end $$;

