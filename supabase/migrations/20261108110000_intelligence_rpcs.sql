create or replace function public.intel_agent_prune(p_evidence_days int default 45) returns int
language plpgsql security definer set search_path = pg_catalog, public as $$
declare v_org uuid := public.intel_agent_org(); n int;
begin
  delete from public.intel_evidence e using public.intel_prospects p
   where e.prospect_id = p.id and e.organization_id = v_org and p.status in ('rejected','suppressed')
     and e.fetched_at < now() - make_interval(days => greatest(p_evidence_days, 7));
  get diagnostics n = row_count;
  delete from public.intel_jobs where organization_id = v_org and state in ('succeeded','cancelled') and finished_at < now() - interval '14 days';
  return n;
end $$;

-- Grants: every intel_* / _intel_* function ---------------------------------------------------------
do $$
declare r record;
begin
  for r in select p.oid::regprocedure as sig, p.proname
             from pg_proc p join pg_namespace n on n.oid = p.pronamespace
            where n.nspname = 'public' and (p.proname like 'intel\_%' or p.proname like '\_intel\_%' or p.proname = 'crm_find_lead_duplicates')
  loop
    execute format('revoke all on function %s from public, anon', r.sig);
    if r.proname like '\_intel\_%' then
      execute format('revoke all on function %s from authenticated', r.sig);
    else
      execute format('grant execute on function %s to authenticated', r.sig);
    end if;
  end loop;
end $$;

