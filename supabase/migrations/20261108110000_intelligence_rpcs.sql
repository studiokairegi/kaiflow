create or replace function public.intel_agent_confirm_send(p_message_id uuid, p_zoho_message_id text, p_rfc_message_id text, p_thread_id text, p_sent_at timestamptz default null) returns jsonb
language plpgsql security definer set search_path = pg_catalog, public as $$
declare v_org uuid := public.intel_agent_org(); m public.intel_messages; v_when timestamptz := coalesce(p_sent_at, now());
begin
  select * into m from public.intel_messages where id = p_message_id and organization_id = v_org for update;
  if not found then raise exception 'message not found'; end if;
  if m.state = 'sent' then return jsonb_build_object('ok', true, 'idempotent', true); end if;
  if m.state not in ('reserved','sending','unknown') then raise exception 'message is % and cannot be confirmed', m.state; end if;
  update public.intel_messages set state = 'sent', sent_at = v_when, zoho_message_id = nullif(p_zoho_message_id, ''), rfc_message_id = nullif(p_rfc_message_id, ''),
         zoho_thread_id = nullif(p_thread_id, ''), error = null where id = m.id;
  if m.kind in ('initial','followup') then
    update public.intel_prospects set status = case when status in ('replied','closed') then status else 'contacted' end, updated_at = now() where id = m.prospect_id;
    if m.lead_id is not null then
      update public.leads
         set emails = case when jsonb_array_length(emails) > m.step then
                        jsonb_set(jsonb_set(jsonb_set(emails, array[m.step::text, 'sent'], 'true'::jsonb), array[m.step::text, 'dateSent'], to_jsonb(to_char(v_when, 'YYYY-MM-DD'))),
                                  array[m.step::text, 'message'], to_jsonb(m.body_text)) else emails end,
             last_contacted_at = v_when,
             stage = case when m.kind = 'initial' and stage = 'pool' then 'cold_email' else stage end,
             stage_changed_at = case when m.kind = 'initial' and stage = 'pool' then now() else stage_changed_at end
       where id = m.lead_id;
    end if;
  end if;
  perform public._intel_log(v_org, 'agent', 'confirm_send', 'message', m.id::text, jsonb_build_object('kind', m.kind));
  return jsonb_build_object('ok', true);
end $$;

