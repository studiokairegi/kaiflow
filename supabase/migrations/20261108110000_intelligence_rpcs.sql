create or replace function public.intel_admin_review_prospect(p_prospect_id uuid, p_action text, p_lead_id uuid default null) returns jsonb
language plpgsql security definer set search_path = pg_catalog, public as $$
declare v_org uuid := public.intel_admin_org(); p public.intel_prospects; s public.intel_settings; v_lead uuid;
begin
  select * into p from public.intel_prospects where id = p_prospect_id and organization_id = v_org for update;
  if not found then raise exception 'prospect not found'; end if;
  select * into s from public.intel_settings where organization_id = v_org;
  if p_action = 'approve' then
    update public.intel_prospects set status = 'qualified', review_reason = '', updated_at = now() where id = p.id;
  elsif p_action = 'reject' then
    update public.intel_prospects set status = 'rejected', updated_at = now() where id = p.id;
  elsif p_action = 'use_lead' then
    if not exists (select 1 from public.leads l where l.id = p_lead_id and l.user_id = s.owner_user_id) then raise exception 'lead not found'; end if;
    update public.intel_prospects set lead_id = p_lead_id, status = 'lead_linked', review_reason = '', updated_at = now() where id = p.id;
    v_lead := p_lead_id;
  elsif p_action = 'create_new' then
    v_lead := public._intel_create_ai_lead(v_org, p.id, auth.uid());
  else
    raise exception 'unknown action';
  end if;
  perform public._intel_log(v_org, 'admin', 'review_prospect_' || p_action, 'prospect', p.id::text, jsonb_build_object('lead_id', v_lead));
  return jsonb_build_object('ok', true, 'lead_id', v_lead);
end $$;

create or replace function public.intel_admin_review_message(p_message_id uuid, p_action text, p_subject text default null, p_body text default null) returns jsonb
language plpgsql security definer set search_path = pg_catalog, public as $$
declare v_org uuid := public.intel_admin_org(); m public.intel_messages;
begin
  select * into m from public.intel_messages where id = p_message_id and organization_id = v_org for update;
  if not found then raise exception 'message not found'; end if;
  if m.direction <> 'outbound' then raise exception 'only outbound messages can be reviewed'; end if;
  if p_action = 'approve' then
    if m.state <> 'pending_approval' then raise exception 'message is not waiting for approval'; end if;
    update public.intel_messages set state = 'approved', auto_sent = false where id = m.id;
  elsif p_action = 'discard' then
    if m.state in ('reserved','sending','sent','unknown') then raise exception 'message already in flight'; end if;
    update public.intel_messages set state = 'discarded' where id = m.id;
  elsif p_action = 'edit' then
    if m.state not in ('draft','pending_approval','failed') then raise exception 'message can no longer be edited'; end if;
    update public.intel_messages set subject = coalesce(left(p_subject, 300), subject), body_text = coalesce(left(p_body, 20000), body_text),
           state = 'pending_approval', error = null where id = m.id;
  elsif p_action = 'retry' then
    if m.state <> 'failed' then raise exception 'only failed messages can be retried'; end if;
    update public.intel_messages set state = 'approved', error = null where id = m.id;
  else
    raise exception 'unknown action';
  end if;
  perform public._intel_log(v_org, 'admin', 'review_message_' || p_action, 'message', m.id::text, '{}'::jsonb);
  return jsonb_build_object('ok', true);
end $$;

-- A message left in 'unknown' (crash mid-send) is resolved by the administrator if the worker could not verify it.
create or replace function public.intel_admin_resolve_unknown(p_message_id uuid, p_outcome text) returns jsonb
language plpgsql security definer set search_path = pg_catalog, public as $$
declare v_org uuid := public.intel_admin_org();
begin
  if p_outcome not in ('sent','not_sent') then raise exception 'outcome must be sent or not_sent'; end if;
  update public.intel_messages
     set state = case when p_outcome = 'sent' then 'sent' else 'failed' end,
         sent_at = case when p_outcome = 'sent' then coalesce(sent_at, now()) else sent_at end,
         error = case when p_outcome = 'sent' then null else 'administrator confirmed it was not sent' end
   where id = p_message_id and organization_id = v_org and state = 'unknown';
  if not found then raise exception 'no unknown message with that id'; end if;
  perform public._intel_log(v_org, 'admin', 'resolve_unknown_' || p_outcome, 'message', p_message_id::text, '{}'::jsonb);
  return jsonb_build_object('ok', true);
end $$;

create or replace function public.intel_admin_compose_reply(p_prospect_id uuid, p_subject text, p_body text) returns uuid
