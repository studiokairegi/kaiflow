create or replace function public.intel_agent_record_inbound(
  p_zoho_message_id text, p_rfc_message_id text, p_in_reply_to text, p_references text, p_from_email text,
  p_subject text, p_body_text text, p_received_at timestamptz, p_thread_id text, p_token text)
returns jsonb language plpgsql security definer set search_path = pg_catalog, public as $$
declare v_org uuid := public.intel_agent_org(); v_from text := public.intel_norm_email(p_from_email);
        v_prospect uuid; v_lead uuid; v_type text; v_id uuid; v_ref text;
begin
  if coalesce(p_zoho_message_id, '') = '' then raise exception 'zoho message id required'; end if;
  select id into v_id from public.intel_messages where organization_id = v_org and zoho_message_id = p_zoho_message_id;
  if v_id is not null then return jsonb_build_object('message_id', v_id, 'duplicate', true); end if;

  -- match: our token, then Message-ID threading headers, then the prospect's own address
  if coalesce(p_token, '') <> '' then
    select prospect_id into v_prospect from public.intel_messages where organization_id = v_org and token = p_token;
  end if;
  if v_prospect is null then
    select m.prospect_id into v_prospect from public.intel_messages m
     where m.organization_id = v_org and m.direction = 'outbound' and m.rfc_message_id is not null
       and (m.rfc_message_id = p_in_reply_to or position(m.rfc_message_id in coalesce(p_references, '')) > 0)
     limit 1;
  end if;
  if v_prospect is null and v_from <> '' then
    select p.id into v_prospect from public.intel_prospects p
     where p.organization_id = v_org and p.contact_email = v_from
       and exists (select 1 from public.intel_messages m where m.prospect_id = p.id and m.direction = 'outbound' and m.state in ('sent','unknown'))
     limit 1;
  end if;
  if v_prospect is not null then select lead_id, type into v_lead, v_type from public.intel_prospects where id = v_prospect; end if;

  insert into public.intel_messages(organization_id, prospect_id, lead_id, campaign_type, direction, kind, state, to_email, from_email, subject, body_text,
                                    idempotency_key, rfc_message_id, in_reply_to, references_ids, zoho_message_id, zoho_thread_id, received_at)
  values (v_org, v_prospect, v_lead, v_type, 'inbound', 'inbound', 'received', '', v_from, left(coalesce(p_subject, ''), 300), left(coalesce(p_body_text, ''), 20000),
          'in:' || p_zoho_message_id, nullif(p_rfc_message_id, ''), nullif(p_in_reply_to, ''), nullif(p_references, ''), p_zoho_message_id, nullif(p_thread_id, ''), coalesce(p_received_at, now()))
  returning id into v_id;
  return jsonb_build_object('message_id', v_id, 'duplicate', false, 'prospect_id', v_prospect, 'matched', v_prospect is not null);
exception when unique_violation then
  select id into v_id from public.intel_messages where organization_id = v_org and (zoho_message_id = p_zoho_message_id or rfc_message_id = nullif(p_rfc_message_id, ''));
  return jsonb_build_object('message_id', v_id, 'duplicate', true);
end $$;

create or replace function public.intel_agent_classify_inbound(p_message_id uuid, p_class text, p_confidence numeric, p_escalate boolean, p_summary text, p_related_email text default null) returns jsonb
language plpgsql security definer set search_path = pg_catalog, public as $$
declare v_org uuid := public.intel_agent_org(); m public.intel_messages; p public.intel_prospects; v_event text; v_title text; v_name text; v_who text;
begin
  if p_class not in ('positive','meeting_request','pricing','negotiation','portfolio_request','project_opportunity','rejection','unsubscribe','ambiguous','complaint','bounce','out_of_office','auto_reply','other') then
    raise exception 'unknown class';
  end if;
  select * into m from public.intel_messages where id = p_message_id and organization_id = v_org and direction = 'inbound' for update;
  if not found then raise exception 'inbound message not found'; end if;
  update public.intel_messages set classification = p_class, classification_confidence = p_confidence, escalated = coalesce(p_escalate, false), summary = left(coalesce(p_summary, ''), 500) where id = m.id;
  if m.prospect_id is not null then select * into p from public.intel_prospects where id = m.prospect_id; end if;
  v_name := coalesce(p.name, m.from_email, 'a prospect');

  if p_class in ('unsubscribe','rejection') and m.from_email <> '' then
    insert into public.intel_suppressions(organization_id, kind, value, reason, source) values (v_org, 'email', m.from_email, p_class, 'agent') on conflict do nothing;
  end if;
  if p_class = 'bounce' and coalesce(p_related_email, '') <> '' then
    insert into public.intel_suppressions(organization_id, kind, value, reason, source) values (v_org, 'email', public.intel_norm_email(p_related_email), 'bounce', 'agent') on conflict do nothing;
    update public.intel_prospects set status = 'closed', updated_at = now() where organization_id = v_org and contact_email = public.intel_norm_email(p_related_email) and status in ('contacted','lead_linked');
  end if;
  if m.prospect_id is not null and p_class not in ('out_of_office','auto_reply','bounce') then
    update public.intel_prospects set status = case when p_class in ('rejection','unsubscribe') then 'closed' else 'replied' end, updated_at = now() where id = m.prospect_id and status not in ('closed');
    -- stop anything still queued for this prospect
    update public.intel_messages set state = 'discarded', error = 'prospect replied' where prospect_id = m.prospect_id and direction = 'outbound' and kind in ('initial','followup') and state in ('draft','pending_approval','approved');
    if p_class in ('positive','meeting_request','pricing','negotiation','portfolio_request','project_opportunity') and m.lead_id is not null then
      update public.leads set stage = 'responded', stage_changed_at = now(), last_contacted_at = now() where id = m.lead_id and stage in ('pool','cold_email');
    end if;
  end if;

  v_event := case p_class when 'positive' then 'intel_positive_reply' when 'meeting_request' then 'intel_meeting_request' when 'pricing' then 'intel_pricing_inquiry'
                          when 'negotiation' then 'intel_negotiation' when 'portfolio_request' then 'intel_portfolio_request' when 'project_opportunity' then 'intel_project_opportunity'
                          when 'rejection' then 'intel_rejection' when 'unsubscribe' then 'intel_unsubscribe' when 'bounce' then 'intel_bounce'
                          when 'ambiguous' then 'intel_needs_review' when 'complaint' then 'intel_needs_review' else null end;
  if v_event is not null then
    v_title := case p_class when 'positive' then 'Positive reply from ' when 'meeting_request' then 'Meeting request from ' when 'pricing' then 'Pricing enquiry from '
                            when 'negotiation' then 'Negotiation with ' when 'portfolio_request' then 'Portfolio request from ' when 'project_opportunity' then 'Project opportunity: '
                            when 'rejection' then 'Declined by ' when 'unsubscribe' then 'Unsubscribe from ' when 'bounce' then 'Email bounced: ' else 'Needs your review: ' end || v_name;
    perform public._intel_notify(v_org, v_event, v_title, coalesce(nullif(p_summary, ''), 'Open the conversation to read the message.'), m.lead_id, m.prospect_id, m.id, 'in:' || coalesce(m.zoho_message_id, m.id::text));
  end if;
  perform public._intel_log(v_org, 'agent', 'classify_inbound', 'message', m.id::text, jsonb_build_object('class', p_class, 'escalate', p_escalate));
  return jsonb_build_object('ok', true, 'notified', v_event is not null);
end $$;

create or replace function public.intel_agent_followup_candidates(p_limit int default 20) returns jsonb
language plpgsql stable security definer set search_path = pg_catalog, public as $$
declare v_org uuid := public.intel_agent_org(); s public.intel_settings; v_today date;
begin
  select * into s from public.intel_settings where organization_id = v_org;
  v_today := public._intel_today(v_org);
  return coalesce((select jsonb_agg(x) from (
    select p.id as prospect_id, p.name, i.sent_at
      from public.intel_prospects p
      join lateral (select max(sent_at) as sent_at from public.intel_messages m where m.prospect_id = p.id and m.kind = 'initial' and m.state = 'sent') i on i.sent_at is not null
     where p.organization_id = v_org and p.status = 'contacted'
       and public.intel_business_days_between((i.sent_at at time zone s.timezone)::date, v_today) >= s.followup_business_days
       and (select count(*) from public.intel_messages f where f.prospect_id = p.id and f.kind = 'followup' and f.state not in ('discarded','failed')) < s.max_followups
       and not exists (select 1 from public.intel_messages r where r.prospect_id = p.id and r.direction = 'inbound')
     order by i.sent_at limit greatest(1, least(p_limit, 100))) x), '[]'::jsonb);
end $$;

