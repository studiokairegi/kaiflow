-- KairFlow Intelligence: privileged RPCs.
--   intel_admin_*  : the administrator (admin AND active Master User, via intel_require_authorized()).
--   intel_agent_*  : the worker's SEPARATE identity (intel_settings.agent_user_id). It can run only
--                    these functions; it has no table access, cannot delete anything, cannot touch
--                    other modules, and is never considered authorized for the admin functions.
--   _intel_*       : internal helpers, not executable by clients.
-- Requires the two previous Intelligence migrations. Safe to run more than once.
begin;

-- Context helpers ---------------------------------------------------------------------------------
create or replace function public.intel_admin_org() returns uuid
language plpgsql stable security definer set search_path = pg_catalog, public as $$
declare v uuid;
begin
  perform public.intel_require_authorized();
  select m.organization_id into v
    from public.studio_memberships m
   where m.user_id = auth.uid() and m.role = 'master_user' and m.status = 'active'
   order by exists (select 1 from public.intel_settings s where s.organization_id = m.organization_id) desc, m.created_at
   limit 1;
  if v is null then raise exception 'KairFlow Intelligence is restricted.' using errcode = '42501'; end if;
  return v;
end $$;

create or replace function public.intel_agent_org() returns uuid
language plpgsql stable security definer set search_path = pg_catalog, public as $$
declare v uuid;
begin
  if auth.uid() is null then raise exception 'Not authenticated' using errcode = '28000'; end if;
  select organization_id into v from public.intel_settings where agent_user_id = auth.uid();
  if v is null then raise exception 'Not the Intelligence agent' using errcode = '42501'; end if;
  return v;
end $$;

create or replace function public._intel_today(p_org uuid) returns date
language sql stable security definer set search_path = pg_catalog, public as $$
  select (now() at time zone s.timezone)::date from public.intel_settings s where s.organization_id = p_org
$$;

create or replace function public._intel_effective_initial_cap(p_org uuid) returns int
language plpgsql stable security definer set search_path = pg_catalog, public as $$
declare s public.intel_settings; v_days int;
begin
  select * into s from public.intel_settings where organization_id = p_org;
  if not found then return 0; end if;
  if not s.warmup_enabled then return s.daily_initial_cap; end if;
  v_days := case when s.warmup_started_on is null then 0 else greatest(public._intel_today(p_org) - s.warmup_started_on, 0) end;
  return least(s.daily_initial_cap, 5 + 5 * (v_days / 7));
end $$;

create or replace function public._intel_deny(p_reason text) returns jsonb language sql immutable as $$
  select jsonb_build_object('ok', false, 'reason', p_reason)
$$;

-- Internal: create an AI-attributed lead for a prospect (the ONLY place that sets the marker).
create or replace function public._intel_create_ai_lead(p_org uuid, p_prospect uuid, p_created_by uuid)
returns uuid language plpgsql security definer set search_path = pg_catalog, public as $$
declare s public.intel_settings; p public.intel_prospects; v_lead uuid; v_notes text;
begin
  select * into s from public.intel_settings where organization_id = p_org;
  select * into p from public.intel_prospects where id = p_prospect and organization_id = p_org;
  if s.organization_id is null or p.id is null then raise exception 'prospect not found'; end if;
  v_notes := 'AI generated by KairFlow Intelligence (' || p.type || '). Score ' || coalesce(p.score::text, 'n/a') ||
             '. Verified facts and sources are on the Intelligence prospect record.';
  perform set_config('intel.agent_write', 'on', true);
  insert into public.leads (user_id, company_name, contact_person, email, website, country, notes,
                            stage, channel, contacted_via, priority, source_kind, intel_prospect_id, created_by)
  values (s.owner_user_id, p.name, p.contact_name, p.contact_email, p.website, p.country, v_notes,
          'pool', 'Cold Email', 'Email', 'warm', 'ai_intelligence', p.id, p_created_by)
  returning id into v_lead;
  perform set_config('intel.agent_write', 'off', true);
  update public.intel_prospects set lead_id = v_lead, status = 'lead_linked', updated_at = now() where id = p.id;
  return v_lead;
end $$;

